# Dictionary is a collection of key-value pairs. It is defined using curly braces {} and each key is unique. Dictionaries are mutable, meaning you can add, remove, or modify key-value pairs after creation.

student = {"name": "Shawon", "age": 23, "department": "CSE"}

print(student["name"])
print(student["age"])

student["age"] = 24
student["university"] = "Eastern University"

print(student)
