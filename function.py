# Define a function in Python using the 'def' keyword. Functions are reusable blocks of code that perform a specific task. They can take input parameters and return output values.


def values(a, b):
    sum = a + b
    sub = a - b
    multiplication = a * b
    division = a / b
    print("The sum of", a, "and", b, "is:", sum)
    print("The difference of", a, "and", b, "is:", sub)
    print("The product of", a, "and", b, "is:", multiplication)
    print("The quotient of", a, "and", b, "is:", division)
    print(".......................")


values(10, 5)
values(20, 4)
